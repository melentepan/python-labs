# Задание 8. Дано целое число в диапазоне 10–40, определяющее количество учебных заданий по
# некоторой теме. Вывести строку-описание указанного количества заданий, обеспечив правильное
# согласование числа со словами «учебное задание», например: 18 — «восемнадцать учебных заданий».


def solve(number):
    teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать']
    tens = ['', '', 'двадцать', 'тридцать', 'сорок']
    units = ['', 'одно', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять']
    if number < 10 or number > 40:
        print('Количество должно быть от 10 до 40.')
    else:
        if number < 20:
            words = teens[number - 10]
        else:
            words = tens[number // 10]
            if number % 10 != 0:
                words += ' ' + units[number % 10]
        if number < 20:
            ending = 'учебных заданий'
        elif number % 10 == 1:
            ending = 'учебное задание'
        elif 2 <= number % 10 <= 4:
            ending = 'учебных задания'
        else:
            ending = 'учебных заданий'
        print(words, ending)


