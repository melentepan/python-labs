# Задание 4. Даны координаты точки, не лежащей на координатных осях OX и OY. Определить номер
# координатной четверти, в которой находится данная точка


def solve(x, y):
    if x == 0 or y == 0:
        print('Точка лежит на координатной оси.')
    elif x > 0 and y > 0:
        print('Координатная четверть: 1')
    elif x < 0 and y > 0:
        print('Координатная четверть: 2')
    elif x < 0 and y < 0:
        print('Координатная четверть: 3')
    else:
        print('Координатная четверть: 4')
