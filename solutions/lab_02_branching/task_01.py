# Задание 1. Даны две переменные целого типа: A и B. Если их значения не равны, то присвоить
# каждой переменной большее из этих значений, а если равны, то присвоить переменным нулевые
# значения. Вывести новые значения переменных A и B.


def solve(a, b):
    if a == b:
        a = 0
        b = 0
    elif a > b:
        b = a
    else:
        a = b
    print('A =', a)
    print('B =', b)
