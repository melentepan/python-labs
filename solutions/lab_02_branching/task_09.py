# Задание 9. Дано целое число в диапазоне 100–999. Вывести строку-описание данного числа,
# например: 256 — «двести пятьдесят шесть», 814 — «восемьсот четырнадцать».


def solve(number):
    hundreds = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот']
    tens = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто']
    teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать']
    units = ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять']
    if number < 100 or number > 999:
        print('Число должно быть в диапазоне от 100 до 999.')
    else:
        words = hundreds[number // 100]
        remainder = number % 100
        if 10 <= remainder <= 19:
            words += ' ' + teens[remainder - 10]
        else:
            if remainder >= 20:
                words += ' ' + tens[remainder // 10]
            if remainder % 10 != 0:
                words += ' ' + units[remainder % 10]
        print(words)
