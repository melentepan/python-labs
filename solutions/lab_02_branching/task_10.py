# Задание 10. В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов,
# обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный. В каждом подцикле годы
# носят названия животных: крысы, коровы, тигра, зайца, дракона, змеи, лошади, овцы, обезьяны,
# курицы, собаки и свиньи. По номеру года определить его название, если 1984 год — начало цикла:
# «год зеленой крысы».


def solve(year):
    animals = ['крысы', 'коровы', 'тигра', 'зайца', 'дракона', 'змеи', 'лошади', 'овцы', 'обезьяны', 'курицы', 'собаки', 'свиньи']
    feminine_colors = ['зеленой', 'красной', 'желтой', 'белой', 'черной']
    masculine_colors = ['зеленого', 'красного', 'желтого', 'белого', 'черного']
    cycle_year = (year - 1984) % 60
    animal_index = cycle_year % 12
    color_index = cycle_year // 12
    if 2 <= animal_index <= 4:
        color = masculine_colors[color_index]
    else:
        color = feminine_colors[color_index]
    print('год', color, animals[animal_index])
