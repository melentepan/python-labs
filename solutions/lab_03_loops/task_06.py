# Задание 6. Даны целые положительные числа A и B (A < B). Вывести все целые числа от A до B
# включительно; при этом каждое число должно выводиться столько раз, каково его значение
# (например, число 3 выводится 3 раза).


def solve(a, b):
    for number in range(a, b + 1):
        for i in range(number):
            print(number, end=' ')
        print()


