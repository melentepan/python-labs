# Задание 8. Дано целое число N (> 1). Вывести наименьшее из целых чисел K, для которых сумма 1 +
# 2 + . . . + K будет больше или равна N, и саму эту сумму.


def solve(n):
    k = 0
    total = 0
    while total < n:
        k += 1
        total += k
    print('K =', k)
    print('Сумма:', total)
