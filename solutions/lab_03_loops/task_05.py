# Задание 5. Дано вещественное число A и целое число N (> 0). Используя один цикл, найти значение
# выражения 1 − A + A^2 − A^3 + . . . ± A^N . Условный оператор не использовать.


def solve(a, n):
    term = 1.0
    total = 1.0
    for i in range(1, n + 1):
        term *= -a
        total += term
    print('Значение выражения:', total)


