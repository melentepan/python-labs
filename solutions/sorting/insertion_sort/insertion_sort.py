# Задание. Используя словесное и визуальное описание, реализовать сортировку вставками.

# Сортировка вставками поддерживает упорядоченную левую часть списка.
# Берём очередной элемент и временно сохраняем его в current.
# Сдвигаем вправо элементы слева, которые больше current.
# В освободившуюся позицию вставляем current. Повторяем до конца списка.
# Пример: [5, 1, 4, 2] -> [1, 5, 4, 2] -> [1, 4, 5, 2] -> [1, 2, 4, 5].
# Список изменяется на месте. Время: O(N²), для готового списка O(N).
# Дополнительная память: O(1). Равные элементы сохраняют взаимный порядок.


def insertion_sort(numbers):
    for i in range(1, len(numbers)):
        current = numbers[i]
        j = i - 1
        while j >= 0 and numbers[j] > current:
            numbers[j + 1] = numbers[j]
            j -= 1
        numbers[j + 1] = current
    return numbers

def solve(numbers):
    insertion_sort(numbers)
    print('Отсортированный массив:', *numbers)
