# Задание. Используя словесное и визуальное описание, реализовать сортировку пузырьком.

# Сортировка пузырьком сравнивает соседние элементы и меняет их местами,
# если левый больше правого. После прохода наибольший элемент оказывается
# в конце рассматриваемой части. Следующий проход будет на один элемент короче.
# Если обменов не было, список уже упорядочен и работа завершается.
# Пример проходов: [5, 1, 4, 2] -> [1, 4, 2, 5] -> [1, 2, 4, 5].
# Список изменяется на месте. Время: O(N²), для готового списка O(N).
# Дополнительная память: O(1). Равные элементы сохраняют взаимный порядок.


def bubble_sort(numbers):
    for end in range(len(numbers) - 1, 0, -1):
        swapped = False
        for i in range(end):
            if numbers[i] > numbers[i + 1]:
                numbers[i], numbers[i + 1] = (numbers[i + 1], numbers[i])
                swapped = True
        if not swapped:
            break
    return numbers

def solve(numbers):
    bubble_sort(numbers)
    print('Отсортированный массив:', *numbers)
