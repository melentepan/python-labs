# Задание 1. Дано целое число N (> 0). Сформировать и вывести целочисленный массив размера N,
# содержащий N первых положительных нечетных чисел: 1, 3, 5, . . . .


def solve(n):
    numbers = []
    for i in range(n):
        numbers.append(2 * i + 1)
    print('Массив:', *numbers)


